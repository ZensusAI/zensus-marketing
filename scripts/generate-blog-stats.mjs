// Derive per-post stats (word count, in-article image URLs) from the blog
// MDX sources and emit them as a generated TypeScript module. BlogPost.tsx
// folds these into BlogPosting JSON-LD (wordCount + full image array) so
// every future post gets complete schema for free.
//
// Runs at the front of `npm run build`; the output is committed so dev
// servers work without a prior build step.

import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { SITE_URL } from "./site.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const blogDir = join(__dirname, "..", "src", "content", "blog");
const outPath = join(__dirname, "..", "src", "generated", "blog-stats.ts");

const files = (await readdir(blogDir)).filter((f) => f.endsWith(".mdx")).sort();
const publicDir = join(__dirname, "..", "public");

// Pixel size of a WebP from its header (VP8, VP8L or VP8X), so the article
// hero can reserve the image's own shape instead of letterboxing it.
function webpSize(buf) {
  if (buf.toString("ascii", 0, 4) !== "RIFF" || buf.toString("ascii", 8, 12) !== "WEBP") return null;
  const chunk = buf.toString("ascii", 12, 16);
  if (chunk === "VP8 ") return { width: buf.readUInt16LE(26) & 0x3fff, height: buf.readUInt16LE(28) & 0x3fff };
  if (chunk === "VP8L") {
    const bits = buf.readUInt32LE(21);
    return { width: (bits & 0x3fff) + 1, height: ((bits >> 14) & 0x3fff) + 1 };
  }
  if (chunk === "VP8X") return { width: buf.readUIntLE(24, 3) + 1, height: buf.readUIntLE(27, 3) + 1 };
  return null;
}

const stats = {};
for (const file of files) {
  const slug = file.replace(/\.mdx$/, "");
  const source = await readFile(join(blogDir, file), "utf-8");

  // The cover (meta.thumbnail) is the article's hero image, so it leads the
  // BlogPosting image list, followed by the figures in the body.
  const thumbnailPath = source.match(/thumbnail:\s*['"]([^'"]+)['"]/)?.[1];
  const thumbnail = thumbnailPath?.endsWith(".webp") ? webpSize(await readFile(join(publicDir, thumbnailPath))) : null;
  const images = [
    ...new Set([
      ...(thumbnailPath ? [thumbnailPath] : []),
      ...[...source.matchAll(/src="(\/blog\/[^"]+\.(?:webp|png|jpe?g))"/g)].map((m) => m[1]),
    ]),
  ].map((path) => `${SITE_URL}${path}`);

  const text = source
    .replace(/^import\s.*$/gm, "")
    .replace(/export const meta = \{[\s\S]*?\n\};?/, "")
    .replace(/<[^>]+>/g, " ")
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/[#*`>]/g, " ");
  const wordCount = text.split(/\s+/).filter(Boolean).length;

  stats[slug] = thumbnail ? { wordCount, images, thumbnail } : { wordCount, images };
}

const banner =
  "// Generated by scripts/generate-blog-stats.mjs. Do not edit by hand.\n" +
  "// Regenerate with: node scripts/generate-blog-stats.mjs\n";
const body = `export const blogStats: Record<string, { wordCount: number; images: string[]; thumbnail?: { width: number; height: number } }> = ${JSON.stringify(stats, null, 2)};\n`;
await writeFile(outPath, banner + body, "utf-8");
console.log(`[blog-stats] wrote ${outPath} (${files.length} posts)`);
